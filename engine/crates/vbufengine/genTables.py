"""Writes src/tables.rs from linuxPlatform.atspi.roles and libatspi's enums, so that the buffer's
renderer gives the same role and state numbers as NVDA's objects. Run inside the rig:
  nix develop ROOT -c ROOT/tests/linux/rig python3 engine/crates/vbufengine/genTables.py ROOT OUT.rs
"""

import gettext
import sys
from pathlib import Path

ROOT = Path(sys.argv[1])
sys.path.insert(0, str(ROOT / "source"))
from linuxPlatform import bootstrap

bootstrap.install()
gettext.install("nvda", names=("pgettext", "ngettext", "npgettext"))
import globalVars

globalVars.appDir = str(ROOT / "source")
import gi

gi.require_version("Atspi", "2.0")
from gi.repository import Atspi  # noqa: I001
from controlTypes import Role, State
from linuxPlatform.atspi.roles import ROLES, STATES

lines = ["// Generated by genTables.py from linuxPlatform.atspi.roles; do not edit.", ""]
names = []
roles = []
for i in range(Atspi.ROLE_COUNT):
	name = Atspi.role_get_name(Atspi.Role(i)) or ""
	names.append(name)
	roles.append(ROLES.get(name, Role.UNKNOWN).value)
lines.append(f"pub const ROLE_NAMES: [&str; {len(names)}] = [")
lines += [f'    "{n}",' for n in names]
lines.append("];")
lines.append(f"pub const NVDA_ROLES: [u32; {len(roles)}] = [")
lines += [f"    {r}," for r in roles]
lines.append("];")
states = []
for nick, state in STATES.items():
	bit = int(getattr(Atspi.StateType, nick.upper().replace("-", "_")))
	states.append((bit, state.value))
lines.append(f"pub const NVDA_STATES: [(u32, u64); {len(states)}] = [")
lines += [f"    ({b}, {s})," for b, s in states]
lines.append("];")
for name in (
	"UNAVAILABLE",
	"INVISIBLE",
	"OFFSCREEN",
	"COLLAPSED",
	"LINKED",
	"HALFCHECKED",
	"INDETERMINATE",
	"FOCUSABLE",
	"READONLY",
	"EDITABLE",
	"CHECKED",
	"PRESSED",
	"CHECKABLE",
):
	lines.append(f"pub const STATE_{name}: u64 = {State[name].value};")
for name in (
	"UNKNOWN",
	"LINK",
	"BUTTON",
	"TOGGLEBUTTON",
	"MENUITEM",
	"GRAPHIC",
	"HEADING",
	"TAB",
	"MENUBUTTON",
	"STATICTEXT",
	"EDITABLETEXT",
	"TABLE",
	"TABLECELL",
	"TABLEROWHEADER",
	"TABLECOLUMNHEADER",
	"SECTION",
	"DOCUMENT",
	"INTERNALFRAME",
	"SEPARATOR",
	"COMBOBOX",
	"TEXTFRAME",
	"CHECKBOX",
	"CHECKMENUITEM",
	"ICON",
	"LIST",
	"LISTITEM",
):
	lines.append(f"pub const ROLE_{name}: u32 = {Role[name].value};")
for nick in (
	"enabled",
	"sensitive",
	"visible",
	"showing",
	"expandable",
	"expanded",
	"indeterminate",
	"editable",
	"multi-line",
):
	bit = int(getattr(Atspi.StateType, nick.upper().replace("-", "_")))
	lines.append(f"pub const ATSPI_{nick.upper().replace('-', '_')}: u32 = {bit};")
Path(sys.argv[2]).write_text("\n".join(lines) + "\n")
print("wrote", sys.argv[2])
